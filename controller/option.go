// GroupOptionsUpdateRequest 表示一次原子保存所需的完整分组配置。
type GroupOptionsUpdateRequest struct {
	GroupRatio              string   `json:"GroupRatio"`
	GroupDisplayNames       string   `json:"GroupDisplayNames"`
	TopupGroupRatio         string   `json:"TopupGroupRatio"`
	UserUsableGroups        string   `json:"UserUsableGroups"`
	GroupGroupRatio         string   `json:"GroupGroupRatio"`
	AutoGroups              string   `json:"AutoGroups"`
	DefaultUseAutoGroup     bool     `json:"DefaultUseAutoGroup"`
	GroupSpecialUsableGroup string   `json:"GroupSpecialUsableGroup"`
	ChangedKeys             []string `json:"changedKeys"`
}

// validateGroupOptionsUpdate 校验一次保存涉及的全部分组配置。
func validateGroupOptionsUpdate(request GroupOptionsUpdateRequest) error {
	if err := ratio_setting.CheckGroupRatio(request.GroupRatio); err != nil {
		return err
	}
	if err := setting.ValidateGroupDisplayNamesJSONString(request.GroupDisplayNames); err != nil {
		return err
	}

	var groupRatio map[string]float64
	var topupGroupRatio map[string]float64
	var userUsableGroups map[string]string
	var groupGroupRatio map[string]map[string]float64
	var autoGroups []string
	var groupSpecialUsableGroup map[string]map[string]string
	jsonValues := []struct {
		value  string
		target any
	}{
		{request.GroupRatio, &groupRatio},
		{request.TopupGroupRatio, &topupGroupRatio},
		{request.UserUsableGroups, &userUsableGroups},
		{request.GroupGroupRatio, &groupGroupRatio},
		{request.AutoGroups, &autoGroups},
		{request.GroupSpecialUsableGroup, &groupSpecialUsableGroup},
	}
	for _, jsonValue := range jsonValues {
		if err := common.UnmarshalJsonStr(jsonValue.value, jsonValue.target); err != nil {
			return err
		}
	}

	identifiers := make([]string, 0, len(groupRatio)+len(topupGroupRatio)+len(userUsableGroups))
	for identifier := range groupRatio {
		identifiers = append(identifiers, identifier)
	}
	for identifier := range topupGroupRatio {
		identifiers = append(identifiers, identifier)
	}
	for identifier := range userUsableGroups {
		identifiers = append(identifiers, identifier)
	}
	identifiers = append(identifiers, autoGroups...)
	for userGroup, targetRatios := range groupGroupRatio {
		identifiers = append(identifiers, userGroup)
		for targetGroup := range targetRatios {
			identifiers = append(identifiers, targetGroup)
		}
	}
	for userGroup, rules := range groupSpecialUsableGroup {
		identifiers = append(identifiers, userGroup)
		for rawTargetGroup := range rules {
			targetGroup := strings.TrimPrefix(strings.TrimPrefix(rawTargetGroup, "+:"), "-:")
			identifiers = append(identifiers, targetGroup)
		}
	}
	for _, identifier := range identifiers {
		if strings.TrimSpace(identifier) == "" {
			return fmt.Errorf("group identifier cannot be blank")
		}
	}
	return nil
}

// buildChangedGroupOptionValues 将前端字段白名单转换为实际存储键和值。
func buildChangedGroupOptionValues(request GroupOptionsUpdateRequest) (map[string]string, []string, error) {
	values := make(map[string]string, len(request.ChangedKeys))
	storageKeys := make([]string, 0, len(request.ChangedKeys))
	for _, key := range request.ChangedKeys {
		var storageKey string
		var value string
		switch key {
		case "GroupRatio":
			storageKey, value = key, request.GroupRatio
		case "GroupDisplayNames":
			storageKey, value = key, request.GroupDisplayNames
		case "TopupGroupRatio":
			storageKey, value = key, request.TopupGroupRatio
		case "UserUsableGroups":
			storageKey, value = key, request.UserUsableGroups
		case "GroupGroupRatio":
			storageKey, value = key, request.GroupGroupRatio
		case "AutoGroups":
			storageKey, value = key, request.AutoGroups
		case "DefaultUseAutoGroup":
			storageKey, value = key, strconv.FormatBool(request.DefaultUseAutoGroup)
		case "GroupSpecialUsableGroup":
			storageKey = "group_ratio_setting.group_special_usable_group"
			value = request.GroupSpecialUsableGroup
		default:
			return nil, nil, fmt.Errorf("unsupported group option key: %s", key)
		}
		if _, exists := values[storageKey]; exists {
			continue
		}
		values[storageKey] = value
		storageKeys = append(storageKeys, storageKey)
	}
	if len(values) == 0 {
		return nil, nil, fmt.Errorf("changedKeys cannot be empty")
	}
	return values, storageKeys, nil
}

// UpdateGroupOptions 通过单个事务保存相互关联的分组配置。
func UpdateGroupOptions(c *gin.Context) {
	var request GroupOptionsUpdateRequest
	if err := common.DecodeJson(c.Request.Body, &request); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"success": false, "message": "无效的参数"})
		return
	}
	if err := validateGroupOptionsUpdate(request); err != nil {
		c.JSON(http.StatusOK, gin.H{"success": false, "message": err.Error()})
		return
	}

	values, storageKeys, err := buildChangedGroupOptionValues(request)
	if err != nil {
		c.JSON(http.StatusOK, gin.H{"success": false, "message": err.Error()})
		return
	}
	if err := model.UpdateOptionsBulk(values); err != nil {
		common.ApiError(c, err)
		return
	}

	recordManageAudit(c, "option.group.update", map[string]interface{}{
		"keys": storageKeys,
	})
	c.JSON(http.StatusOK, gin.H{"success": true, "message": ""})
}

func isPaymentComplianceOptionKey(key string) bool {
	return strings.HasPrefix(key, "payment_setting.compliance_")
}

func isPositiveOptionValue(value string) bool {
	intValue, err := strconv.Atoi(strings.TrimSpace(value))
	if err == nil {
		return intValue > 0
	}
	floatValue, err := strconv.ParseFloat(strings.TrimSpace(value), 64)
	return err == nil && floatValue > 0
}

func collectModelNamesFromOptionValue(raw string, modelNames map[string]struct{}) {
	if strings.TrimSpace(raw) == "" {
		return
	}

	var parsed map[string]any
	if err := common.UnmarshalJsonStr(raw, &parsed); err != nil {
		return
	}

	for modelName := range parsed {
		modelNames[modelName] = struct{}{}
	}
}

func buildCompletionRatioMetaValue(optionValues map[string]string) string {
	modelNames := make(map[string]struct{})
	for _, key := range completionRatioMetaOptionKeys {
		collectModelNamesFromOptionValue(optionValues[key], modelNames)
	}

	meta := make(map[string]ratio_setting.CompletionRatioInfo, len(modelNames))
	for modelName := range modelNames {
		meta[modelName] = ratio_setting.GetCompletionRatioInfo(modelName)
	}

	jsonBytes, err := common.Marshal(meta)
	if err != nil {
		return "{}"
	}
	return string(jsonBytes)
}

func GetOptions(c *gin.Context) {
	var options []*model.Option
	optionValues := make(map[string]string)
	common.OptionMapRWMutex.Lock()
	for k, v := range common.OptionMap {
		if k == "theme.frontend" {
			continue
		}
		value := common.Interface2String(v)
		isSensitiveKey := strings.HasSuffix(k, "Token") ||
			strings.HasSuffix(k, "Secret") ||
			strings.HasSuffix(k, "Key") ||
			strings.HasSuffix(k, "secret") ||
			strings.HasSuffix(k, "api_key")
		if isSensitiveKey {
			continue
		}
		options = append(options, &model.Option{
			Key:   k,
			Value: value,
		})
		for _, optionKey := range completionRatioMetaOptionKeys {
			if optionKey == k {
				optionValues[k] = value
				break
			}
		}
	}
	common.OptionMapRWMutex.Unlock()
	options = append(options, &model.Option{
		Key:   "CompletionRatioMeta",
		Value: buildCompletionRatioMetaValue(optionValues),
	})
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    options,
	})
}

type OptionUpdateRequest struct {
	Key   string `json:"key"`
	Value any    `json:"value"`
}

func UpdateOption(c *gin.Context) {
	var option OptionUpdateRequest
	err := common.DecodeJson(c.Request.Body, &option)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{
			"success": false,
			"message": "无效的参数",
		})
		return
	}
	switch option.Value.(type) {
	case bool:
		option.Value = common.Interface2String(option.Value.(bool))
	case float64:
		option.Value = common.Interface2String(option.Value.(float64))
	case int:
		option.Value = common.Interface2String(option.Value.(int))
	default:
		option.Value = fmt.Sprintf("%v", option.Value)
	}
	switch option.Key {
	case "QuotaForInviter", "QuotaForInvitee":
		if isPositiveOptionValue(option.Value.(string)) && !operation_setting.IsPaymentComplianceConfirmed() {
			common.ApiErrorI18n(c, i18n.MsgPaymentComplianceRequired)
			return
		}
	default:
		if isPaymentComplianceOptionKey(option.Key) {
			common.ApiErrorMsg(c, "合规确认字段不允许通过通用设置接口修改")
			return
		}
	}
	switch option.Key {
	case "GitHubOAuthEnabled":
		if option.Value == "true" && common.GitHubClientId == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 GitHub OAuth，请先填入 GitHub Client Id 以及 GitHub Client Secret！",
			})
			return
		}
	case "discord.enabled":
		if option.Value == "true" && system_setting.GetDiscordSettings().ClientId == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 Discord OAuth，请先填入 Discord Client Id 以及 Discord Client Secret！",
			})
			return
		}
	case "oidc.enabled":
		if option.Value == "true" && system_setting.GetOIDCSettings().ClientId == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 OIDC 登录，请先填入 OIDC Client Id 以及 OIDC Client Secret！",
			})
			return
		}
	case "LinuxDOOAuthEnabled":
		if option.Value == "true" && common.LinuxDOClientId == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 LinuxDO OAuth，请先填入 LinuxDO Client Id 以及 LinuxDO Client Secret！",
			})
			return
		}
	case "EmailDomainRestrictionEnabled":
		if option.Value == "true" && len(common.EmailDomainWhitelist) == 0 {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用邮箱域名限制，请先填入限制的邮箱域名！",
			})
			return
		}
	case "WeChatAuthEnabled":
		if option.Value == "true" && common.WeChatServerAddress == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用微信登录，请先填入微信登录相关配置信息！",
			})
			return
		}
	case "TurnstileCheckEnabled":
		if option.Value == "true" && common.TurnstileSiteKey == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 Turnstile 校验，请先填入 Turnstile 校验相关配置信息！",
			})

			return
		}
	case "TelegramOAuthEnabled":
		if option.Value == "true" && common.TelegramBotToken == "" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "无法启用 Telegram OAuth，请先填入 Telegram Bot Token！",
			})
			return
		}
	case "theme.frontend":
		if option.Value != "default" {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "Classic 前端已移除，主题只能设置为 default",
			})
			return
		}
	case "GroupRatio":
		err = ratio_setting.CheckGroupRatio(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "GroupDisplayNames":
		err = setting.ValidateGroupDisplayNamesJSONString(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "gemini.safety_settings":
		err = model_setting.ValidateGeminiSafetySettings(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "claude.default_max_tokens":
		err = model_setting.ValidateClaudeDefaultMaxTokens(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case operation_setting.ToolPriceOptionKey:
		err = operation_setting.ValidateToolPricesJSON(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "ImageRatio":
		err = ratio_setting.UpdateImageRatioByJSONString(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "图片倍率设置失败: " + err.Error(),
			})
			return
		}
	case "AudioRatio":
		err = ratio_setting.UpdateAudioRatioByJSONString(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "音频倍率设置失败: " + err.Error(),
			})
			return
		}
	case "AudioCompletionRatio":
		err = ratio_setting.UpdateAudioCompletionRatioByJSONString(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "音频补全倍率设置失败: " + err.Error(),
			})
			return
		}
	case "CreateCacheRatio":
		err = ratio_setting.UpdateCreateCacheRatioByJSONString(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": "缓存创建倍率设置失败: " + err.Error(),
			})
			return
		}
	case "ModelRequestRateLimitGroup":
		err = setting.CheckModelRequestRateLimitGroup(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "AutomaticDisableStatusCodes":
		_, err = operation_setting.ParseHTTPStatusCodeRanges(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "AutomaticRetryStatusCodes":
		_, err = operation_setting.ParseHTTPStatusCodeRanges(option.Value.(string))
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "console_setting.api_info":
		err = console_setting.ValidateConsoleSettings(option.Value.(string), "ApiInfo")
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "console_setting.announcements":
		err = console_setting.ValidateConsoleSettings(option.Value.(string), "Announcements")
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "console_setting.faq":
		err = console_setting.ValidateConsoleSettings(option.Value.(string), "FAQ")
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	case "console_setting.uptime_kuma_groups":
		err = console_setting.ValidateConsoleSettings(option.Value.(string), "UptimeKumaGroups")
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	}
	err = model.UpdateOption(option.Key, option.Value.(string))
	if err != nil {
		common.ApiError(c, err)
		return
	}
	// 出于安全考虑只记录被修改的配置项名称，不记录配置值（可能含密钥等敏感信息）。
	recordManageAudit(c, "option.update", map[string]interface{}{
		"key": option.Key,
	})
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
	})
}
