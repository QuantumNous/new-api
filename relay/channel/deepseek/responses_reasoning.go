package deepseek

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/url"
	"strings"

	"github.com/QuantumNous/new-api/common"
	relaycommon "github.com/QuantumNous/new-api/relay/common"
	"github.com/tidwall/gjson"
	"github.com/tidwall/sjson"
)

// FinalizeResponsesRequest normalizes the effective history and thinking mode
// after channel parameter overrides, preserving unrelated raw JSON fields.
func (a *Adaptor) FinalizeResponsesRequest(info *relaycommon.RelayInfo, body []byte) ([]byte, error) {
	baseURL := "https://api.deepseek.com"
	if info != nil && info.ChannelMeta != nil && info.ChannelBaseUrl != "" {
		baseURL = info.ChannelBaseUrl
	}
	upstream, parseErr := url.Parse(baseURL)
	official := parseErr == nil && upstream.Scheme == "https" &&
		strings.EqualFold(upstream.Hostname(), "api.deepseek.com") &&
		(upstream.Port() == "" || upstream.Port() == "443")
	if !official || gjson.GetBytes(body, "reasoning.effort").String() == "none" {
		return body, nil
	}
	input := []byte(gjson.GetBytes(body, "input").Raw)
	normalized, err := normalizeResponsesReasoningReplay(input)
	if err != nil {
		return nil, err
	}
	if bytes.Equal(input, normalized) {
		return body, nil
	}
	return sjson.SetRawBytes(body, "input", normalized)
}

// DeepSeek's stateless Responses API requires plaintext reasoning before an
// assistant tool step, including a step resumed after a tool result.
// Reproduced against the official endpoint on 2026-10-28:
// https://github.com/yetone/magpie/commit/f4cc7459ea0d5e39409e481d5d31db6d2bace64b
// A space is a protocol placeholder, never reconstructed model reasoning.
func normalizeResponsesReasoningReplay(input json.RawMessage) (json.RawMessage, error) {
	root := gjson.ParseBytes(input)
	if !root.IsArray() {
		return input, nil
	}
	// Keep raw slices into one string instead of copying every history item.
	// GJSON is permissive; retain strict JSON validation before raw splicing.
	if !gjson.ValidBytes(input) {
		var invalid []json.RawMessage
		return nil, common.Unmarshal(input, &invalid)
	}
	values := root.Array()
	items := make([]string, len(values))
	for i, value := range values {
		items[i] = value.Raw
	}
	placeholder := `{"type":"reasoning","summary":[],"content":[{"type":"reasoning_text","text":" "}]}`
	out := make([]string, 0, len(items))
	changed, afterTool := false, false
	for i := 0; i < len(items); {
		start, firstReasoning := i, -1
		hasCall, hasMessage := false, false
		for i < len(items) {
			item := gjson.Parse(items[i])
			kind, role := item.Get("type").String(), item.Get("role").String()
			if kind == "function_call" || kind == "custom_tool_call" {
				hasCall = true
			} else if (kind == "message" || kind == "") && role == "assistant" {
				hasMessage = true
			} else if kind == "reasoning" {
				if firstReasoning < 0 {
					firstReasoning = i
				}
				content := item.Get("content")
				// Leave invalid non-array content to normal upstream validation.
				if content.IsArray() || content.Type == gjson.Null {
					parts := content.Array()
					hasText := false
					for j, part := range parts {
						if part.Get("type").String() != "reasoning_text" {
							continue
						}
						hasText = true
						text := part.Get("text")
						if text.Type != gjson.Null && (text.Type != gjson.String || text.String() != "") {
							continue
						}
						updated, err := sjson.Set(items[i], fmt.Sprintf("content.%d.text", j), " ")
						if err != nil {
							return nil, err
						}
						items[i], changed = updated, true
					}
					if !hasText {
						rawParts := make([]json.RawMessage, 0, len(parts)+1)
						for _, part := range parts {
							rawParts = append(rawParts, json.RawMessage(part.Raw))
						}
						rawParts = append(rawParts, json.RawMessage(`{"type":"reasoning_text","text":" "}`))
						encoded, err := common.Marshal(rawParts)
						if err != nil {
							return nil, err
						}
						updated, err := sjson.SetRaw(items[i], "content", string(encoded))
						if err != nil {
							return nil, err
						}
						items[i], changed = updated, true
					}
				}
			} else {
				break
			}
			i++
		}
		if start == i {
			kind := gjson.Get(items[i], "type").String()
			afterTool = kind == "function_call_output" || kind == "custom_tool_call_output"
			out = append(out, items[i])
			i++
			continue
		}
		if hasCall || (afterTool && hasMessage) {
			if firstReasoning < 0 {
				out = append(out, placeholder)
				changed = true
			} else {
				out = append(out, items[firstReasoning])
				changed = changed || firstReasoning != start
			}
			for j := start; j < i; j++ {
				if j != firstReasoning {
					out = append(out, items[j])
				}
			}
		} else {
			out = append(out, items[start:i]...)
		}
		afterTool = false
	}
	if !changed {
		return input, nil
	}
	// All elements are validated raw JSON or generated by SJSON/common.Marshal.
	// Splice them without decoding large tool outputs or changing number precision.
	size := 2
	for _, item := range out {
		size += len(item) + 1
	}
	result := make([]byte, 0, size)
	result = append(result, '[')
	for i, item := range out {
		if i > 0 {
			result = append(result, ',')
		}
		result = append(result, item...)
	}
	result = append(result, ']')
	return result, nil
}
